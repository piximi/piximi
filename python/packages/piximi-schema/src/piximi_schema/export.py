"""Builds the JSON Schema bundle the frontend generates its types from.

Run as ``piximi-schema-export`` (or ``python -m piximi_schema.export``); the
bundle is checked in and CI fails when it drifts from the models.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from pydantic.json_schema import models_json_schema

from . import PROTOCOL_VERSION
from .base import WireModel
from .entities import ImageSeries
from .events import EVENT_TYPES
from .methods import METHODS, NOTIFICATIONS
from .rpc import (
    ErrorResponseMessage,
    NotificationMessage,
    RequestMessage,
    ResponseMessage,
)
from .segmentation import SegmentationRunRequest

BUNDLE_PATH = Path(__file__).resolve().parents[2] / "schema" / "protocol.schema.json"

# Models not reachable from any method or notification but still part of the
# contract, so the frontend has them too.
STANDALONE: tuple[type[WireModel], ...] = (
    ImageSeries,
    SegmentationRunRequest,
    RequestMessage,
    ResponseMessage,
    ErrorResponseMessage,
    NotificationMessage,
)


def _ref(model: type[WireModel] | None) -> str | None:
    return None if model is None else f"#/$defs/{model.__name__}"


def _all_models() -> list[type[WireModel]]:
    seen: dict[str, type[WireModel]] = {}
    for spec in METHODS:
        for model in (spec.params, spec.result, spec.progress):
            if model is not None:
                seen.setdefault(model.__name__, model)
    for spec in NOTIFICATIONS:
        if spec.params is not None:
            seen.setdefault(spec.params.__name__, spec.params)
    for model in (*EVENT_TYPES, *STANDALONE):
        seen.setdefault(model.__name__, model)
    return list(seen.values())


def _strip_null_from_optionals(schema: dict[str, Any]) -> None:
    """``x: T | None = None`` is emitted as ``anyOf [T, null]``; on the wire an
    unset optional is simply absent, never ``null``, so drop the null branch
    from non-required properties. Gives ``x?: T`` in TypeScript."""
    for definition in schema["$defs"].values():
        required = set(definition.get("required", []))
        for name, prop in definition.get("properties", {}).items():
            if name in required or "anyOf" not in prop:
                continue
            branches = [b for b in prop["anyOf"] if b != {"type": "null"}]
            if len(branches) == len(prop["anyOf"]):
                continue
            replacement = branches[0] if len(branches) == 1 else {"anyOf": branches}
            keep = {k: v for k, v in prop.items() if k not in ("anyOf", "default")}
            prop.clear()
            prop.update({**replacement, **keep})


def _walk(node: Any) -> Any:
    """Yields every dict in the schema, depth first."""
    if isinstance(node, dict):
        yield node
        for value in node.values():
            yield from _walk(value)
    elif isinstance(node, list):
        for value in node:
            yield from _walk(value)


def _for_typescript(schema: dict[str, Any]) -> None:
    """Shapes the schema for json-schema-to-typescript.

    - Field titles go: the generator would turn each into a named alias
      (``Id1``, ``Boundingbox``), when the field type should simply be inlined.
      Titles stay on ``$defs`` entries, where they name the interfaces.
    - Draft 2020-12 ``prefixItems`` tuples become draft-07 ``items`` arrays,
      which is the form the generator reads.
    - ``bytes`` fields travel as msgpack binary; type them as such.
    """
    for definition in schema["$defs"].values():
        for prop in definition.get("properties", {}).values():
            prop.pop("title", None)
    for node in _walk(schema):
        if "prefixItems" in node:
            node["items"] = node.pop("prefixItems")
            node["additionalItems"] = False
        if node.get("type") == "string" and node.get("format") == "binary":
            node.clear()
            node.update({"tsType": "Uint8Array", "description": "msgpack binary"})


def build_bundle() -> dict[str, Any]:
    _, schema = models_json_schema(
        [(model, "validation") for model in _all_models()],
        ref_template="#/$defs/{model}",
    )
    _strip_null_from_optionals(schema)
    _for_typescript(schema)
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "PiximiProtocol",
        "description": "Generated by piximi-schema; do not edit.",
        "type": "object",
        "additionalProperties": False,
        "properties": {},
        "protocolVersion": PROTOCOL_VERSION,
        "$defs": dict(sorted(schema["$defs"].items())),
        "methods": {
            spec.name: {
                "direction": spec.direction,
                "params": _ref(spec.params),
                "result": _ref(spec.result),
                "progress": _ref(spec.progress),
            }
            for spec in METHODS
        },
        "notifications": {
            spec.name: {"direction": spec.direction, "params": _ref(spec.params)}
            for spec in NOTIFICATIONS
        },
    }


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    out = Path(args[0]) if args else BUNDLE_PATH
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(build_bundle(), indent=2) + "\n")
    print(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
