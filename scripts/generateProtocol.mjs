// Regenerates the frontend's wire types from the Python schema package:
//   python/packages/piximi-schema  →  schema/protocol.schema.json
//                                  →  src/core/backend/protocol/{generated,methods}.ts
// Run with `pnpm protocol:gen`; CI fails if the output drifts.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const bundlePath = path.join(
  root,
  "python/packages/piximi-schema/schema/protocol.schema.json",
);
const outDir = path.join(root, "src/core/backend/protocol");

execFileSync("uv", ["run", "--project", "python", "piximi-schema-export"], {
  cwd: root,
  stdio: "inherit",
});

const bundle = JSON.parse(readFileSync(bundlePath, "utf8"));
const { methods, notifications, protocolVersion, ...schema } = bundle;

const banner = [
  "/*",
  " * Generated by scripts/generateProtocol.mjs from python/packages/piximi-schema.",
  " * Do not edit; run `pnpm protocol:gen`.",
  " */",
].join("\n");

const generated = await compile(schema, "PiximiProtocol", {
  bannerComment: banner,
  additionalProperties: false,
  // Emit every $def, not just the ones reachable from the (empty) root.
  unreachableDefinitions: true,
  strictIndexSignatures: false,
});
writeFileSync(path.join(outDir, "generated.ts"), generated);

const typeName = (ref) => (ref ? `P.${ref.split("/").pop()}` : "void");
const entry = (name, spec, keys) =>
  `  "${name}": { ${keys
    .map((key) => `${key}: ${typeName(spec[key])}`)
    .join("; ")}; direction: "${spec.direction}" };`;

const methodsTs = `${banner}
import type * as P from "./generated";

export const PROTOCOL_VERSION = "${protocolVersion}";

/* Requests, keyed by method name. \`progress\` is the \`$/progress\` payload. */
export type ProtocolMethods = {
${Object.entries(methods)
  .map(([name, spec]) => entry(name, spec, ["params", "result", "progress"]))
  .join("\n")}
};

/* Notifications (no response), keyed by method name. */
export type ProtocolNotifications = {
${Object.entries(notifications)
  .map(([name, spec]) => entry(name, spec, ["params"]))
  .join("\n")}
};
`;
writeFileSync(path.join(outDir, "methods.ts"), methodsTs);

execFileSync("pnpm", ["exec", "prettier", "--write", "--log-level", "warn", outDir], {
  cwd: root,
  stdio: "inherit",
});
console.log(`wrote ${path.relative(root, outDir)}/{generated,methods}.ts`);
